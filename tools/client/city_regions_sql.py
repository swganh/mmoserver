#!/usr/bin/env python3
"""Write a migration that gives a planet's cities the areas the client uses.

    python3 -I tools/client/city_regions_sql.py tatooine datatables/clientregion/tatooine.iff

The client's region table (datatables/clientregion/<planet>.iff) lists the
named areas it shows "You have entered ..." for, as circles: a centre and a
radius. Each city in the cities table gets a new planet_regions row with its
circle (stored as width 0, height = diameter). The city's old region is kept:
it is the larger no-build area around the city (build = 1).

A city the client draws as several circles gets the largest; the others are
listed as comments (the server has one area per city).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import datatable  # noqa: E402

PLANETS = {"corellia": 0, "dantooine": 1, "dathomir": 2, "endor": 3, "lok": 4,
           "naboo": 5, "rori": 6, "talus": 7, "tatooine": 8, "yavin4": 9}


def main(planet, path):
    planet_id = PLANETS[planet]
    columns, rows = datatable.read(path)
    name_col, x_col, z_col, r_col = (columns.index(c) for c in ("Name", "X", "Z", "Radius"))

    circles = {}
    for row in rows:
        file, _, name = row[name_col].lstrip("@").partition(":")
        circles.setdefault((file, name), []).append((row[x_col], row[z_col], row[r_col]))

    print("-- %s: city areas from the client's datatables/clientregion/%s.iff" % (planet, planet))
    print("-- (generated by tools/client/city_regions_sql.py). The cities' old regions stay")
    print("-- as their no-build areas.")
    for (file, name), parts in circles.items():
        parts.sort(key=lambda c: -c[2])
        x, z, radius = parts[0]
        print()
        print("-- %s: centre %g, %g, radius %g" % (name, x, z, radius))
        for other in parts[1:]:
            print("--   also drawn by the client (not used): centre %g, %g, radius %g" % other)
        print("INSERT INTO swganh.planet_regions (region_name, region_file, x, z, width, height, planet_id, build, no_build_type)")
        print("  VALUES ('%s', '%s', %g, %g, 0, %g, %d, 0, 0);" % (name, file, x, z, radius * 2, planet_id))
        print("UPDATE swganh.cities c JOIN swganh.planet_regions r ON c.city_region = r.region_id")
        print("  SET c.city_region = LAST_INSERT_ID()")
        print("  WHERE c.planet_id = %d AND r.region_name = '%s' AND r.build != 0;" % (planet_id, name))


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] not in PLANETS:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
