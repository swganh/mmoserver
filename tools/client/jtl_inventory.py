#!/usr/bin/env python3
"""List the Jump to Lightspeed content in a client, as Markdown.

    python3 -I tools/client/jtl_inventory.py <client folder> > jtl_inventory.md

Reads the client's .tre archives (tools/client/tre.py) and reports, by
area, how many files of the expansion the client has: space zones, ship
and component object templates, schematics, datatables (with their row
counts and columns), string files and space quests. Anything with
"space" or "ship" in its path that fits no area is listed at the end, so
nothing is missed.

The report holds file names, counts and column names only, so it can be
committed (docs/JTL.md). The client's files themselves are not.
"""

import collections
import fnmatch
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import datatable  # noqa: E402
import tre  # noqa: E402

# (area, patterns); a file goes to the first area that matches.
AREAS = [
    ("Space zones (terrain)", ["terrain/space_*"]),
    ("Space zone buildouts and snapshots", ["datatables/buildout/space_*", "snapshot/space_*"]),
    ("Ship datatables", ["datatables/ship/*", "datatables/space/*", "datatables/space_*/*"]),
    ("Space quest datatables", ["datatables/spacequest/*", "datatables/space_quest/*"]),
    ("Space mobiles and AI", ["datatables/space_mobile/*", "datatables/space_ai/*", "datatables/space_content/*"]),
    ("Ship object templates", ["object/ship/*"]),
    ("Ship component and part templates", ["object/tangible/ship/*"]),
    ("Ship control devices", ["object/intangible/ship/*"]),
    ("Ship schematics", ["object/draft_schematic/space/*", "object/draft_schematic/ship/*"]),
    ("Space stations and space buildings", ["object/static/space/*", "object/building/*space*"]),
    ("Ship strings", ["string/en/space/*", "string/en/ship*"]),
    ("Space quest strings", ["string/en/spacequest/*", "string/en/space_quest/*"]),
    ("Pilot and shipwright skill data", ["datatables/skill/*pilot*", "datatables/skill/*shipwright*",
                                         "string/en/skl_*pilot*"]),
]
KINDS = (".iff", ".stf", ".trn", ".ws", ".tab")


def area_of(name):
    for area, patterns in AREAS:
        if any(fnmatch.fnmatchcase(name, p) for p in patterns):
            return area
    return None


def subfolder(name, depth):
    parts = name.split("/")
    return "/".join(parts[:min(depth, len(parts) - 1)]) + "/"


def describe_datatable(client, name):
    try:
        columns, rows = datatable.parse(client.read(name))
    except Exception as e:  # not every .iff under datatables/ is a table
        return "not read (%s)" % type(e).__name__
    shown = ", ".join(columns[:12]) + (", ..." if len(columns) > 12 else "")
    return "%d rows; %s" % (len(rows), shown)


def report(client, out):
    areas = collections.OrderedDict((a, []) for a, _ in AREAS)
    other = collections.Counter()
    for name in client.names():
        area = area_of(name)
        if area:
            areas[area].append(name)
        elif ("space" in name or "ship" in name) and name.endswith(KINDS) \
                and not name.startswith(("appearance/", "sound/", "texture/", "shader/", "effect/")):
            other[subfolder(name, 3)] += 1

    out.write("# Jump to Lightspeed in the client\n\n")
    out.write("Generated by `tools/client/jtl_inventory.py` from %d archives, %d files.\n\n"
              % (len(client.archives), len(client.files)))
    out.write("| Area | Files |\n|---|---|\n")
    for area, names in areas.items():
        out.write("| %s | %d |\n" % (area, len(names)))
    out.write("| Other paths with space or ship | %d |\n" % sum(other.values()))

    for area, names in areas.items():
        if not names:
            continue
        out.write("\n## %s\n\n" % area)
        if any(n.startswith("datatables/") for n in names):
            for name in names:
                if name.startswith("datatables/") and name.endswith(".iff"):
                    out.write("- `%s`: %s\n" % (name, describe_datatable(client, name)))
                else:
                    out.write("- `%s`\n" % name)
        elif len(names) <= 40:
            for name in names:
                out.write("- `%s`\n" % name)
        else:
            folders = collections.Counter(subfolder(n, 4) for n in names)
            out.write("%d files, by folder:\n\n" % len(names))
            for folder, n in sorted(folders.items()):
                out.write("- `%s`: %d\n" % (folder, n))

    if other:
        out.write("\n## Other paths with space or ship\n\n")
        for folder, n in sorted(other.items()):
            out.write("- `%s`: %d\n" % (folder, n))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    report(tre.Client(sys.argv[1]), sys.stdout)
